#!/usr/bin/env python3
"""Generate the netlist-vs-RTL functional-verification inputs (issue #82).

Everything is generated from design/cells.json (never hand-written per cell):

  * netlist side: one TT transient testbench (`tb_all.cir`) instantiating all
    cells from design/netlists/, each driven through every input vector
    (exhaustive, 2**n), plus one single-corner `klt sim` request
    (`tt.request.json`) that measures every output at the end of every vector
    window. Single corner => runs locally (no batch grid).
  * RTL side: one Verilog testbench (`tb_rtl.v`) over rtl/<cell>.v that prints
    the same truth tables (run with iverilog/vvp by compare.py).

Results are SIMULATED, never measured.

    python3 verification/functional/gen_functional.py          # (re)write
    python3 verification/functional/gen_functional.py --check  # exit 1 if stale
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

VDD = 1.2
WINDOW_NS = 4.0      # one input vector per window
EDGE_NS = 0.1        # input edge time
SAMPLE_NS = 3.8      # sample the output this far into the window
LOAD_FF = 10


def cells() -> list[dict]:
    return json.loads((ROOT / "design" / "cells.json").read_text())["cells"]


def vectors(n: int) -> list[tuple[int, ...]]:
    """All 2**n vectors; vector k has input i = bit (n-1-i) of k (A first = MSB)."""
    return [tuple((k >> (n - 1 - i)) & 1 for i in range(n)) for k in range(1 << n)]


def subckt_ports(name: str) -> list[str]:
    text = (ROOT / "design" / "netlists" / f"{name}.spice").read_text()
    m = re.search(rf"^\.subckt\s+{re.escape(name)}\s+(.*)$", text, re.M | re.I)
    if not m:
        raise SystemExit(f"no .subckt for {name}")
    return m.group(1).split()


def meas_name(cell: str, out: str, k: int) -> str:
    return f"v_{cell}_{out}_{k}".lower()


def build_spice() -> tuple[str, list[dict]]:
    lines = [
        "* Generated by verification/functional/gen_functional.py; do not edit.",
        f"* All cells, every input vector, TT. {VDD} V, window {WINDOW_NS} ns. SIMULATED.",
        f"Vdd vdd 0 {VDD}",
    ]
    meas = []
    for ci, c in enumerate(cells()):
        name, ins, outs = c["name"], c["inputs"], list(c["outputs"])
        vecs = vectors(len(ins))
        lines.append(f".include ../../design/netlists/{name}.spice")
        node = {p: f"c{ci}_{p.lower()}" for p in ins + outs}
        for i, p in enumerate(ins):
            pts = ["0 %s" % (VDD * vecs[0][i])]
            for k in range(1, len(vecs)):
                if vecs[k][i] != vecs[k - 1][i]:
                    t0 = k * WINDOW_NS
                    pts.append(f"{t0}n {VDD * vecs[k - 1][i]}")
                    pts.append(f"{t0 + EDGE_NS}n {VDD * vecs[k][i]}")
            pts.append(f"{len(vecs) * WINDOW_NS}n {VDD * vecs[-1][i]}")
            lines.append(f"V{ci}_{p.lower()} {node[p]} 0 PWL({' '.join(pts)})")
        ports = subckt_ports(name)
        conn = [("vdd" if p == "VDD" else "0" if p == "VSS" else node[p]) for p in ports]
        lines.append(f"X{ci} {' '.join(conn)} {name}")
        for o in outs:
            lines.append(f"C{ci}_{o.lower()} {node[o]} 0 {LOAD_FF}f")
            for k in range(len(vecs)):
                t = k * WINDOW_NS + SAMPLE_NS
                meas.append({"name": meas_name(name, o, k),
                             "spice": f".meas tran {meas_name(name, o, k)} find v({node[o]}) at={t}n"})
    return "\n".join(lines) + "\n", meas


def build_request(meas: list[dict]) -> dict:
    total = len(cells()) and max(len(vectors(len(c["inputs"]))) for c in cells()) * WINDOW_NS
    return {
        "_comment": "Issue #82: TT exhaustive truth-table simulation of all cells from design/netlists/. Single corner, runs local. SIMULATED, never measured. Generated by gen_functional.py; do not edit.",
        "engine": "ngspice",
        "netlist": "tb_all.cir",
        "models": {"pdk": "ihp-sg13cmos5l", "lib": "libs.tech/ngspice/models/cornerMOSlv.lib"},
        "corners": {"process": [{"name": "tt", "sections": ["mos_tt"]}], "temperature_c": [25]},
        "analysis": {"kind": "tran", "args": f"20p {total}n"},
        "measurements": meas,
        "options": {
            "osdi_preload": ["$PDK_ROOT/ihp-sg13cmos5l/libs.tech/ngspice/osdi/psp103.osdi"],
            "timeout_s": 1800,
            "stage_model_inputs": True,
        },
    }


def build_verilog() -> str:
    L = ["// Generated by verification/functional/gen_functional.py; do not edit.",
         "// Exhaustive truth tables of rtl/<cell>.v: `cell out vector value`.",
         "`timescale 1ns/1ps", "module tb_rtl;"]
    body = []
    for ci, c in enumerate(cells()):
        n = len(c["inputs"])
        L.append(f"  reg [{n-1}:0] v{ci};")
        conns = [f".{p}(v{ci}[{n-1-i}])" for i, p in enumerate(c["inputs"])]
        for o in c["outputs"]:
            L.append(f"  wire w{ci}_{o};")
            conns.append(f".{o}(w{ci}_{o})")
        L.append(f"  {c['name']} u{ci} ({', '.join(conns)});")
        loop = [f"    for (k = 0; k < {1 << n}; k = k + 1) begin", f"      v{ci} = k[{n-1}:0]; #1;"]
        for o in c["outputs"]:
            loop.append(f'      $display("{c["name"]} {o} %0d %b", k, w{ci}_{o});')
        loop.append("    end")
        body += loop
    L += ["  integer k;", "  initial begin"] + body + ["    $finish;", "  end", "endmodule"]
    return "\n".join(L) + "\n"


def outputs() -> dict[Path, str]:
    spice, meas = build_spice()
    return {
        HERE / "tb_all.cir": spice,
        HERE / "tt.request.json": json.dumps(build_request(meas), indent=2) + "\n",
        HERE / "tb_rtl.v": build_verilog(),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = False
    for path, text in outputs().items():
        if args.check:
            stale |= not path.exists() or path.read_text() != text
        else:
            path.write_text(text)
    if stale:
        print("stale outputs; rerun gen_functional.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
