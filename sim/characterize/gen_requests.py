#!/usr/bin/env python3
"""Generate the per-corner `klt characterize` requests (issue #27).

One request per ratified Liberty corner (spec/target-spec.md: TT target,
FF/SS stretch), each covering every cell in design/cells.json on the spec's
7x7 slew/load grid. Requests are generated from the cell list, never written
by hand. Results are SIMULATED, never measured.

    python3 sim/characterize/gen_requests.py            # (re)write requests/
    python3 sim/characterize/gen_requests.py --check    # exit 1 if stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

# spec/target-spec.md "Characterization grid" (7 x 7).
SLEW_NS = [0.0186, 0.0966, 0.174, 0.3294, 0.6408, 1.263, 2.5074]
LOAD_PF = [0.001, 0.0234, 0.039, 0.0648, 0.108, 0.18, 0.3]

# spec/target-spec.md "Liberty corners". process = cornerMOSlv.lib section.
CORNERS = {
    "tt": {"name": "tt_1p20v_25c", "process": "mos_tt", "supply_v": 1.20, "temperature_c": 25},
    "ff": {"name": "ff_1p32v_m40c", "process": "mos_ff", "supply_v": 1.32, "temperature_c": -40},
    "ss": {"name": "ss_1p08v_125c", "process": "mos_ss", "supply_v": 1.08, "temperature_c": 125},
}


def build(key: str) -> dict:
    cells = json.loads((ROOT / "design" / "cells.json").read_text())["cells"]
    entries = []
    for c in cells:
        pins = [{"name": p, "direction": "input"} for p in c["inputs"]]
        pins += [{"name": o, "direction": "output", "function": f} for o, f in c["outputs"].items()]
        entries.append({
            "name": c["name"],
            "netlist": f"../../../design/netlists/{c['name']}.spice",
            "pins": pins,
            "power_pins": {"vdd": "VDD", "gnd": "VSS"},
        })
    corner = CORNERS[key]
    return {
        "_comment": f"Issue #27: NLDM characterization of all {len(cells)} cells at {corner['name']}. SIMULATED, never measured. Generated by gen_requests.py; do not edit.",
        "corner": corner,
        "grid": {"input_transition_ns": SLEW_NS, "output_load_pf": LOAD_PF},
        "models": {"pdk": "ihp-sg13cmos5l", "lib": "libs.tech/ngspice/models/cornerMOSlv.lib"},
        "options": {
            "osdi_preload": ["$PDK_ROOT/ihp-sg13cmos5l/libs.tech/ngspice/osdi/psp103.osdi"],
            "stage_model_inputs": True,
        },
        "library": {"name": f"s5l_{corner['name']}"},
        "output": {"outdir": f"../.work/{key}", "lib": f"../records/s5l_{corner['name']}.lib"},
        "cells": entries,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    out = HERE / "requests"
    out.mkdir(exist_ok=True)
    stale = False
    for key in CORNERS:
        text = json.dumps(build(key), indent=2) + "\n"
        path = out / f"{key}.request.json"
        if args.check:
            stale |= not path.exists() or path.read_text() != text
        else:
            path.write_text(text)
    if stale:
        print("stale requests; rerun gen_requests.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
