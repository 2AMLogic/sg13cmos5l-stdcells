#!/usr/bin/env python3
"""Generate one functional Verilog model per cell in design/cells.json.

Usage: gen_models.py [--check] [--catalog PATH] [--outdir DIR]

Writes rtl/<cell>.v for every catalog cell. With --check, writes nothing and
exits 1 if any committed model is missing, stale, or has no catalog cell.

Catalog functions are Liberty style: `!` not, `*` and, `+` or, `^` xor, with
parentheses. `^` may not be mixed with `*` or `+` at one nesting level without
parentheses, so no precedence between them is assumed.
"""
import argparse
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
TOKEN_RE = re.compile(r"\s*(?:([A-Za-z][A-Za-z0-9_]*)|(.))")
VERILOG_OP = {"*": "&", "+": "|", "^": "^"}


def tokenize(expr):
    toks, pos = [], 0
    while pos < len(expr):
        m = TOKEN_RE.match(expr, pos)
        if not m or m.end() == pos:
            break
        toks.append(m.group(1) or m.group(2))
        pos = m.end()
    if expr[pos:].strip():
        raise ValueError(f"cannot tokenize {expr!r}")
    return toks


def parse(expr, pins):
    """Return an AST: pin name, ('!', x), or (op, [operands]) with op in * + ^."""
    toks = tokenize(expr)
    pos = 0

    def peek():
        return toks[pos] if pos < len(toks) else None

    def take():
        nonlocal pos
        t = peek()
        if t is None:
            raise ValueError(f"unexpected end of {expr!r}")
        pos += 1
        return t

    def atom():
        t = take()
        if t == "!":
            return ("!", atom())
        if t == "(":
            node = chain()
            if take() != ")":
                raise ValueError(f"missing ')' in {expr!r}")
            return node
        if t in pins:
            return t
        raise ValueError(f"unknown token {t!r} in {expr!r}")

    def chain():
        first = atom()
        op = peek()
        if op not in VERILOG_OP:
            return first
        operands = [first]
        while peek() == op:
            take()
            operands.append(atom())
        if peek() in VERILOG_OP:
            raise ValueError(f"mixed operators without parentheses in {expr!r}")
        return (op, operands)

    node = chain()
    if pos != len(toks):
        raise ValueError(f"trailing tokens in {expr!r}")
    return node


def to_verilog(node):
    if isinstance(node, str):
        return node
    op, arg = node
    if op == "!":
        return f"~{to_verilog(arg)}"
    return "(" + f" {VERILOG_OP[op]} ".join(to_verilog(a) for a in arg) + ")"


def render(cell):
    pins = set(cell["inputs"])
    outs = cell["outputs"]
    lines = [
        "// Generated by rtl/gen_models.py from design/cells.json; do not edit.",
        "// Functional model only: no timing, no power pins.",
        f"module {cell['name']} (",
        ",\n".join([f"    output {p}" for p in outs] + [f"    input {p}" for p in cell["inputs"]]),
        ");",
    ]
    for p, expr in outs.items():
        lines.append(f"    assign {p} = {to_verilog(parse(expr, pins))};  // {expr}")
    lines += ["endmodule", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="verify committed models are fresh; write nothing")
    ap.add_argument("--catalog", type=pathlib.Path, default=HERE.parent / "design" / "cells.json")
    ap.add_argument("--outdir", type=pathlib.Path, default=HERE)
    args = ap.parse_args(argv)

    cells = json.loads(args.catalog.read_text())["cells"]
    want = {c["name"] + ".v": render(c) for c in cells}

    if args.check:
        errs = []
        for fn, text in sorted(want.items()):
            p = args.outdir / fn
            if not p.is_file():
                errs.append(f"{fn}: missing")
            elif p.read_text() != text:
                errs.append(f"{fn}: stale")
        for p in sorted(args.outdir.glob("s5l_*.v")):
            if p.name not in want:
                errs.append(f"{p.name}: no catalog cell")
        for e in errs:
            print(f"gen_models: {e}", file=sys.stderr)
        if errs:
            return 1
        print(f"gen_models: {len(want)} models fresh")
        return 0

    for fn, text in want.items():
        (args.outdir / fn).write_text(text)
    print(f"gen_models: wrote {len(want)} models to {args.outdir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
